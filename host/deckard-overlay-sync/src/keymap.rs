//! Android's key character map for the shell's keyboard. Android gets the
//! shell's keys as evdev codes (`wayland_keyboard`) and reads them with its
//! own `Generic.kcm`, so a layout's Alt characters (a phone keyboard's
//! numbers and symbols) never arrive. This writes `wayland_keyboard.kcm`:
//! `Generic.kcm` with each character key as the session's XKB keymap
//! (`XKB_DEFAULT_*`, `XKB_CONFIG_EXTRA_PATH`) types it.

