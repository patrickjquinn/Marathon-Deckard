const KEY_LEFTSHIFT: u32 = 42;
const KEY_LEFTALT: u32 = 56;
const KEY_RIGHTALT: u32 = 100;

/// What a key types under each modifier, as far as it types a character.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct Key {
    pub base: Option<char>,
    pub shift: Option<char>,
    pub alt: Option<char>,
    pub shift_alt: Option<char>,
    pub ralt: Option<char>,
}

fn quoted(c: char) -> String {
    match c {
        '\'' => "'\\''".into(),
        '\\' => "'\\\\'".into(),
        '"' => "'\\\"'".into(),
        ' '..='~' => format!("'{c}'"),
        _ => format!("'\\u{:04x}'", u32::from(c)),
    }
}

fn block(name: &str, key: &Key) -> Option<String> {
    let base = key.base?;
    let shift = key.shift.filter(|&s| s != base);
    let letter = base.is_lowercase() && shift.is_some_and(|s| s.to_lowercase().eq([base]));
    let label = if letter { shift.unwrap_or(base) } else { base };
    let mut out = format!("key {name} {{\n");
    let mut line = |behavior: &str, c: char| {
        let _ = writeln!(out, "    {:<36}{}", format!("{behavior}:"), quoted(c));
    };
    line("label", label);
    line("base", base);
    if let Some(shift) = shift {
        if letter {
            line("shift, capslock", shift);
            line("shift+capslock", base);
        } else {
            line("shift", shift);
        }
    }
    if let Some(alt) = key.alt.filter(|&c| c != base) {
        line("alt", alt);
        if let Some(shift_alt) = key.shift_alt {
            line("shift+alt", shift_alt);
        }
    }
    if let Some(ralt) = key.ralt.filter(|&c| c != base && Some(c) != key.alt) {
        line("ralt", ralt);
    }
    out.push('}');
    Some(out)
}

/// `Generic.kcm` with each of `KEYS` replaced by `lookup`'s answer; a key
/// it types nothing for keeps Android's own definition.
pub fn generate(lookup: impl Fn(u32) -> Key) -> String {
    let blocks: Vec<(&str, String)> = KEYS
        .iter()
        .filter_map(|&(code, name)| Some((name, block(name, &lookup(code))?)))
        .collect();
    let mut out = String::from(
        "# Generated by deckard-overlay-sync from the session's XKB keymap,\n\
         # over Generic.kcm (Apache-2.0, the Android Open Source Project).\n",
    );
    let mut lines = GENERIC.lines();
    while let Some(line) = lines.next() {
        let name = line
            .strip_prefix("key ")
            .and_then(|rest| rest.strip_suffix(" {"));
        let Some((_, replacement)) = name.and_then(|n| blocks.iter().find(|(b, _)| *b == n)) else {
            out.push_str(line);
            out.push('\n');
            continue;
        };
        for skipped in lines.by_ref() {
            if skipped == "}" {
                break;
            }
        }
        out.push_str(replacement);
        out.push('\n');
    }
    out
}

/// The session's keymap as `generate` wants it; `None` when no XKB layout
/// is set (Android's own map is right for plain US) or it doesn't compile.
pub fn from_session() -> Option<String> {
    use xkbcommon::xkb;
    std::env::var("XKB_DEFAULT_LAYOUT")
        .ok()
        .filter(|l| !l.is_empty())?;
    let context = xkb::Context::new(xkb::CONTEXT_NO_FLAGS);
    let keymap =
        xkb::Keymap::new_from_names(&context, "", "", "", "", None, xkb::KEYMAP_COMPILE_NO_FLAGS)?;
    let typed = |held: &[u32], code: u32| {
        let mut state = xkb::State::new(&keymap);
        for &m in held {
            state.update_key(xkb::Keycode::new(m + 8), xkb::KeyDirection::Down);
        }
        char::from_u32(state.key_get_utf32(xkb::Keycode::new(code + 8)))
            .filter(|c| !c.is_control() && *c != '\0')
    };
    Some(generate(|code| Key {
        base: typed(&[], code),
        shift: typed(&[KEY_LEFTSHIFT], code),
        alt: typed(&[KEY_LEFTALT], code),
        shift_alt: typed(&[KEY_LEFTSHIFT, KEY_LEFTALT], code),
        ralt: typed(&[KEY_RIGHTALT], code),
    }))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn q25(code: u32) -> Key {
        let key = |base, shift, alt| Key {
            base: Some(base),
            shift: Some(shift),
            alt,
            shift_alt: alt,
            ralt: None,
        };
        match code {
            17 => key('w', 'W', Some('1')),
            50 => key('m', 'M', Some('.')),
            25 => key('p', 'P', Some('@')),
            41 => key('$', '$', Some('`')),
            _ => Key::default(),
        }
    }

    #[test]
    fn alt_characters_reach_android() {
        let map = generate(q25);
        assert!(map.contains(
            "key W {\n    label:                              'W'\n    base:                               'w'\n    shift, capslock:                    'W'\n    shift+capslock:                     'w'\n    alt:                                '1'\n    shift+alt:                          '1'\n}"
        ));
        assert!(map.contains("    alt:                                '.'\n"));
        assert!(map.contains("    alt:                                '@'\n"));
        assert!(map.contains("key GRAVE {\n    label:                              '$'\n    base:                               '$'\n    alt:                                '`'\n    shift+alt:                          '`'\n}"));
    }

    #[test]
    fn keys_the_layout_leaves_out_keep_android_s_own() {
        let map = generate(q25);
        assert!(map.contains("key SPACE {\n    label:                              ' '\n    base:                               ' '\n    alt, meta:                          fallback SEARCH"));
        assert!(map.contains("key A {\n    label:                              'A'\n    base:                               'a'"));
        assert_eq!(map.matches("\nkey W {").count(), 1);
        assert!(map.contains("\ntype FULL\n"));
    }

    #[test]
    fn characters_are_quoted_for_kcm() {
        assert_eq!(quoted('\''), "'\\''");
        assert_eq!(quoted('\\'), "'\\\\'");
        assert_eq!(quoted('é'), "'\\u00e9'");
    }
}
