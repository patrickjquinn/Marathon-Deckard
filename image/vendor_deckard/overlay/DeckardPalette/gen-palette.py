#!/usr/bin/env python3
"""Writes res/values/colors.xml: Android's 65 system_accent/neutral colours
from Marathon's tokens (MColors.qml plus the ambience highlight).

Each palette is a tonal ramp in CIE LCh(ab) where shade N has L* = 100 - N/10
(Material's tone), with the hue and chroma below. The shades Android maps to
Marathon roles in dark mode are then set to the exact token.

Usage: gen-palette.py [--highlight '#7df0d4'] [--mcolors PATH] [--out PATH]
"""
import argparse
import math
import os
import re

SHADES = [0, 10, 50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 1000]
D65 = (0.95047, 1.0, 1.08883)


def srgb_to_linear(c):
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def linear_to_srgb(c):
    return 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055


def f_lab(t):
    return t ** (1 / 3) if t > (6 / 29) ** 3 else t / (3 * (6 / 29) ** 2) + 4 / 29


def f_lab_inv(t):
    return t ** 3 if t > 6 / 29 else 3 * (6 / 29) ** 2 * (t - 4 / 29)


def hex_to_rgb(h):
    h = h.lstrip('#')[-6:]
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def rgb_to_lch(rgb):
    r, g, b = (srgb_to_linear(c) for c in rgb)
    x = 0.4124564 * r + 0.3575761 * g + 0.1804375 * b
    y = 0.2126729 * r + 0.7151522 * g + 0.0721750 * b
    z = 0.0193339 * r + 0.1191920 * g + 0.9503041 * b
    fx, fy, fz = f_lab(x / D65[0]), f_lab(y / D65[1]), f_lab(z / D65[2])
    lum, a, bb = 116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)
    return lum, math.hypot(a, bb), math.degrees(math.atan2(bb, a)) % 360


def lch_to_rgb(lum, chroma, hue):
    a = chroma * math.cos(math.radians(hue))
    b = chroma * math.sin(math.radians(hue))
    fy = (lum + 16) / 116
    x = D65[0] * f_lab_inv(fy + a / 500)
    y = D65[1] * f_lab_inv(fy)
    z = D65[2] * f_lab_inv(fy - b / 200)
    r = 3.2404542 * x - 1.5371385 * y - 0.4985314 * z
    g = -0.9692660 * x + 1.8760108 * y + 0.0415560 * z
    bl = 0.0556434 * x - 0.2040259 * y + 1.0572252 * z
    return tuple(linear_to_srgb(c) if c > 0 else -1.0 for c in (r, g, bl))


def in_gamut(rgb):
    return all(-1e-4 <= c <= 1 + 1e-4 for c in rgb)


def tone(lum, chroma, hue):
    lo, hi = 0.0, chroma
    if in_gamut(lch_to_rgb(lum, hi, hue)):
        lo = hi
    else:
        for _ in range(30):
            mid = (lo + hi) / 2
            if in_gamut(lch_to_rgb(lum, mid, hue)):
                lo = mid
            else:
                hi = mid
    rgb = lch_to_rgb(lum, lo, hue)
    return '#' + ''.join('%02x' % round(min(1, max(0, c)) * 255) for c in rgb)


def ramp(chroma, hue):
    return {s: tone(100 - s / 10, chroma, hue) for s in SHADES}


def mcolors(path):
    tokens = {}
    for name, value in re.findall(r'property color (\w+): "(#[0-9a-fA-F]{6})"', open(path).read()):
        tokens[name] = value.lower()
    return tokens


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    default_mcolors = os.path.expanduser(
        '~/Developer/Marathon-Shell/shell/qml/theme/MColors.qml')
    ap = argparse.ArgumentParser()
    ap.add_argument('--highlight', default='#7df0d4',
                    help="ambience highlight (Silica highlightColor); meridian's by default")
    ap.add_argument('--mcolors', default=default_mcolors)
    ap.add_argument('--out', default=os.path.join(here, 'res/values/colors.xml'))
    args = ap.parse_args()

    tok = mcolors(args.mcolors)
    highlight = args.highlight.lower()
    _, chroma, hue = rgb_to_lch(hex_to_rgb(highlight))
    _, _, grey_hue = rgb_to_lch(hex_to_rgb(tok['elev3']))

    palettes = {
        'accent1': ramp(chroma, hue),
        'accent2': ramp(16, hue),
        'neutral1': ramp(1.5, grey_hue),
        'neutral2': ramp(4, hue),
    }
    # Dark-mode roles (framework DeviceDefault and Material 3) -> MColors.
    exact = {
        ('accent1', 100): highlight,             # framework colorAccent
        ('accent1', 200): highlight,             # Material primary
        ('accent1', 800): tok['textOnAccent'],   # Material onPrimary
        ('neutral1', 100): '#ffffff',            # onSurface: Silica primaryColor
        ('neutral1', 700): tok['elev5'],         # surface variant, header
        ('neutral1', 800): tok['elev3'],         # surface, floating
        ('neutral1', 900): tok['background'] if 'background' in tok else tok['bb10Black'],
        ('neutral2', 200): '#9b9b9b',            # Silica secondaryColor over the floor
        ('neutral2', 700): tok['elev4'],         # Material surfaceVariant
        ('neutral2', 800): tok['elev2'],
        ('neutral2', 900): tok['elev1'],
    }
    for (pal, shade), value in exact.items():
        palettes[pal][shade] = value
    # Marathon has one accent: Material's tertiary (FABs, highlights) is it too.
    palettes = {**palettes, 'accent3': dict(palettes['accent1'])}
    palettes = {k: palettes[k] for k in ('accent1', 'accent2', 'accent3', 'neutral1', 'neutral2')}

    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- Generated by gen-palette.py from MColors.qml and highlight %s. -->' % highlight,
             '<resources>']
    for pal, shades in palettes.items():
        for s in SHADES:
            lines.append('    <color name="system_%s_%d">%s</color>' % (pal, s, shades[s]))
    lines.append('</resources>')
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, 'w') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
