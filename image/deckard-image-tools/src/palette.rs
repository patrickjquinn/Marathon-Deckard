use std::collections::HashMap;
use std::fmt::Write as _;

use deckard_core::palette::{Color, Theme};
use regex::Regex;

/// The theme colours of Marathon's `MColors.qml`.
///
/// # Errors
/// A colour is missing or invalid.
pub fn theme(qml: &str) -> Result<Theme, Box<dyn std::error::Error>> {
    let pattern = Regex::new(r##"property color (\w+): "(#[0-9a-fA-F]{6})""##)?;
    let tokens: HashMap<_, _> = pattern
        .captures_iter(qml)
        .map(|capture| (capture[1].to_owned(), capture[2].to_owned()))
        .collect();
    let color = |name: &str| -> Result<Color, Box<dyn std::error::Error>> {
        let value = tokens
            .get(name)
            .ok_or_else(|| format!("missing theme color {name}"))?;
        Ok(Color::parse(value)?)
    };
    Ok(Theme {
        elevation1: color("elev1")?,
        elevation2: color("elev2")?,
        elevation3: color("elev3")?,
        elevation4: color("elev4")?,
        elevation5: color("elev5")?,
        text_on_accent: color("textOnAccent")?,
        background: color(if tokens.contains_key("background") {
            "background"
        } else {
            "bb10Black"
        })?,
    })
}

/// The Android colour resources for `highlight` on `theme`.
#[must_use]
pub fn render(highlight: Color, theme: Theme) -> String {
    let mut xml = format!(
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by deckard-image-tools from MColors.qml and highlight {}. -->\n<resources>\n",
        highlight.hex()
    );
    for (name, color) in deckard_core::palette::generate(highlight, theme) {
        let _ = writeln!(xml, "    <color name=\"{name}\">{}</color>", color.hex());
    }
    xml.push_str("</resources>\n");
    xml
}

#[cfg(test)]
#[allow(clippy::unwrap_used, reason = "tests parse static theme fixtures")]
mod tests {
    use super::*;

    #[test]
    fn reads_tokens_and_rejects_missing_theme_values() {
        let qml = "property color elev1: \"#0a0a0b\"\nproperty color elev2: \"#121213\"\nproperty color elev3: \"#1c1c1d\"\nproperty color elev4: \"#282829\"\nproperty color elev5: \"#353536\"\nproperty color bb10Black: \"#040404\"\nproperty color textOnAccent: \"#000000\"";
        let parsed = theme(qml).unwrap();
        let xml = render(Color([0x7d, 0xf0, 0xd4]), parsed);
        assert_eq!(xml.matches("<color name=").count(), 65);
        assert!(xml.contains("system_neutral1_900\">#040404"));
        assert!(theme("").is_err());
    }
}
