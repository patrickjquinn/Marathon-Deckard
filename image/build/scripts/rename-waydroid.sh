#!/usr/bin/env bash
# Renames Waydroid to Deckard throughout one Android project: paths first,
# then contents, case kept (WAYDROID, Waydroid/WayDroid, waydroid); the
# id.waydro Java packages become org.marathonos. Links to the Waydroid
# project go to Deckard's. Copyright, SPDX and licence lines and licence
# files keep Waydroid's name. Commits the result.
# Usage: rename-waydroid.sh <project dir>
set -euo pipefail
cd "$1"
LICENCES='(^|/)(LICENSES/|LICEN[CS]E|NOTICE|COPYING)'
NOTICE='[Cc]opyright|SPDX-|[Ll]icen[cs]e'
rename() { sed -e 's#id/waydro/#org/marathonos/#g' -e 's/WAYDROID/DECKARD/g' -e 's/Way[Dd]roid/Deckard/g' -e 's/waydroid/deckard/g'; }
{ git ls-files -z | grep -zE -i 'waydroid|id/waydro/' | grep -zviE "$LICENCES" || true; } | while IFS= read -r -d '' f; do
  n=$(printf '%s' "$f" | rename)
  mkdir -p "$(dirname "$n")"
  git mv -k "$f" "$n"
done
{ git grep -zIilE 'waydroid|id[./]waydro[./]' | grep -zviE "$LICENCES" || true; } | xargs -0 -r sed -i -E \
  -e "/$NOTICE/!{" \
  -e 's#id([./])waydro([./])#org\1marathonos\2#g' \
  -e 's#https?://[A-Za-z0-9./_-]*[Ww]ay[Dd]roid[A-Za-z0-9./_#-]*#https://github.com/patrickjquinn/Marathon-Deckard#g' \
  -e 's/WAYDROID/DECKARD/g' -e 's/Way[Dd]roid/Deckard/g' -e 's/waydroid/deckard/g' \
  -e '}'
find . -depth -type d -empty -not -path './.git*' -delete
git add -u
git commit -q -m "Rename Waydroid to Deckard" -m "Generated by Marathon-Deckard image/build/scripts/rename-waydroid.sh."
git grep -IiE 'waydroid|waydro\b' | grep -vE "$NOTICE" | grep -vE "^[^:]*$LICENCES" | cut -c1-120 || echo "no waydroid left in $(pwd)"
